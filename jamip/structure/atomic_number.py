def get_element_color_and_radius(element_symbol):
    radius = vesta_atomic_radii.get(element_symbol, 0.5 + 0.02*number[element_symbol])
    # 优先使用VESTA配色
    if element_symbol in vesta_cpk_colors:
        rgb = vesta_cpk_colors[element_symbol]
    
    # 处理同位素 (如 D/T 视为 H)
    if element_symbol in ('D', 'T'):
        rgb = vesta_cpk_colors['H']
    
    # 自动生成策略
    atomic_number = number[element_symbol]  # 需要pymatgen支持
    if atomic_number > 92:  # 超铀元素
        rgb = (0.8, 0.0, 0.8)  # 紫色

    color = f'rgb({int(rgb[0]*255)},{int(rgb[1]*255)},{int(rgb[2]*255)})'
    
    return color, radius